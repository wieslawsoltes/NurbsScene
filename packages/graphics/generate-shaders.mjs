#!/usr/bin/env node
/** Emit distributable ESM from the authoritative Uno/standalone WGSL sources. */
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const definitions = [
  ['scene', 'WGSL'], ['bloom', 'BLOOM_WGSL'], ['composite', 'COMPOSITE_WGSL'],
];
const sources = definitions.map(([name, variable]) => ({
  name, variable,
  text: readFileSync(new URL(`../../src/NurbsScene.Rendering/Shaders/${name}.wgsl`, import.meta.url), 'utf8'),
}));
const hashes = Object.fromEntries(sources.map(({ name, text }) =>
  [name, createHash('sha256').update(text).digest('hex')]));
const output = '// Generated by node packages/graphics/generate-shaders.mjs. Do not edit.\n' +
  '// Authoritative source: src/NurbsScene.Rendering/Shaders/*.wgsl\n' +
  sources.map(({ variable, text }) => `export const ${variable} = ${JSON.stringify(text)};\n`).join('') +
  `export const SHADER_SOURCE_SHA256 = Object.freeze(${JSON.stringify(hashes, null, 2)});\n` +
  'export const SHADERS = Object.freeze({ scene: WGSL, bloom: BLOOM_WGSL, composite: COMPOSITE_WGSL });\n';
const destination = new URL('./shaders.js', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(destination, 'utf8') !== output) {
    throw new Error('Packaged WGSL is stale. Run node packages/graphics/generate-shaders.mjs and commit shaders.js.');
  }
  console.log('PASS: packaged WGSL matches every authoritative shader byte.');
} else {
  writeFileSync(destination, output);
  console.log('Generated the three canonical WebGPU shader modules.');
}
